export function tracksForAlbum(albumId: string): Track[] {
  const album = ALBUM_BY_ID.get(albumId);
  if (!album) return [];
  return album.trackIds.map(id => TRACK_BY_ID.get(id)).filter((t): t is Track => Boolean(t));
}

